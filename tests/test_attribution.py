r"""Attribution compliance: the code must honour what NOTICE promises.

NOTICE (Apache 2.0, Section 4(d)) commits the "Created by Lorenzo
Serafini" attribution to be shown in FOUR end-user-visible places:

    1. the application header/banner        (gui/app.py)
    2. the splash screen                     (gui/splash.py)
    3. the --version / about output          (hawk.py)
    4. any report/export footer              (modules/report/render.py)

The banner was the only one that actually carried it; the other three
promised more than the code delivered.  These tests pin the attribution
in place so a future edit cannot silently drop it back below the NOTICE.

Headless by design: the --version path is exercised in-process with a
stubbed customtkinter (hawk.py runs its dependency check at import, so a
subprocess would die on the missing GUI toolkit before reaching
--version); the report footers render with no GUI at all; and the splash
(a customtkinter subclass that cannot import headless) is checked at the
source-shape level, like test_argus_teaser_version.py does for target_bar.
"""

import contextlib
import io
import os
import sys
import types
import unittest

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, ROOT)

from utils.config import APP_NAME, APP_VERSION          # noqa: E402

try:                                        # HTML is the only format
    import jinja2                           # with a third-party dep
    _HAS_JINJA2 = True
except Exception:
    _HAS_JINJA2 = False

_ATTRIBUTION = "Created by Lorenzo Serafini"


def _src(rel):
    with open(os.path.join(ROOT, rel), encoding="utf-8") as f:
        return f.read()


# ─── Point 3 — the --version / about output ────────────────────────────────

class VersionOutputAttributionTests(unittest.TestCase):
    """`hawk.py --version` must print the attribution next to the version.

    hawk.py checks for customtkinter at import time, so we make the import
    succeed headless by stubbing it when it is genuinely absent; the
    --version branch prints and exits before any customtkinter symbol is
    touched, so the stub never has to do anything."""

    def setUp(self):
        self._saved_hawk = sys.modules.pop("hawk", None)
        try:
            import customtkinter  # noqa: F401
            self._stubbed = False
        except Exception:
            sys.modules["customtkinter"] = types.ModuleType("customtkinter")
            self._stubbed = True

    def tearDown(self):
        sys.modules.pop("hawk", None)
        if self._stubbed:
            sys.modules.pop("customtkinter", None)
        if self._saved_hawk is not None:
            sys.modules["hawk"] = self._saved_hawk

    def test_version_output_includes_attribution(self):
        import hawk
        saved_argv = sys.argv
        sys.argv = ["hawk.py", "--version"]
        buf = io.StringIO()
        try:
            with contextlib.redirect_stdout(buf):
                with self.assertRaises(SystemExit) as cm:
                    hawk.main()
        finally:
            sys.argv = saved_argv

        self.assertEqual(cm.exception.code, 0)
        out = buf.getvalue()
        self.assertIn(f"HAWK v{APP_VERSION}", out)
        self.assertIn(_ATTRIBUTION, out)


# ─── Point 4 — the report / export footer ──────────────────────────────────

class ReportFooterAttributionTests(unittest.TestCase):
    """Both the Markdown and the HTML deliverable footers must carry the
    attribution.  No GUI, no customtkinter — the whole render path is
    headless by design (same as test_report_engine.py)."""

    def _sections(self):
        from utils.session import Session
        from modules.report import engine
        from modules.report.model import ReportContext
        ctx = ReportContext(Session("10.10.10.5"))
        return ctx, engine.build_sections(ctx)

    def test_markdown_footer_has_attribution(self):
        from modules.report import render
        ctx, sections = self._sections()
        body = render.render_markdown(ctx, sections)
        self.assertIn(
            f"Generated by {APP_NAME} v{APP_VERSION} - {_ATTRIBUTION}", body)

    @unittest.skipUnless(_HAS_JINJA2, "jinja2 not installed")
    def test_html_footer_has_attribution(self):
        from modules.report import render
        ctx, sections = self._sections()
        html = render.render_html(ctx, sections)
        self.assertIn(f"&middot; {_ATTRIBUTION}</footer>", html)


# ─── Point 2 — the splash screen (source-shape: cannot import headless) ─────

class SplashAttributionTests(unittest.TestCase):
    """gui/splash.py subclasses customtkinter and cannot import headless,
    so we assert the attribution lives on the version LABEL — not merely
    in the file's copyright header, which already carries the phrase."""

    def test_splash_version_line_has_attribution(self):
        src = _src("gui/splash.py")
        self.assertRegex(
            src, r"v\{APP_VERSION\}.*" + _ATTRIBUTION,
            "splash version line must carry the attribution")


if __name__ == "__main__":
    unittest.main()
